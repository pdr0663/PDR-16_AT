  EDIT-HEAD @ BEGIN DUP WHILE DUP EDIT-TRIM-LEN DUP ET2 ! OVER EDIT-LINE-TEXT ET2 @ ET4 @
  WRITE-LINE DUP IF DROP ET4 @ CLOSE-FILE DROP EDIT-MSG-WRITE EDIT-MSG ! 1 EXIT THEN DROP @
  REPEAT DROP ET4 @ FLUSH-FILE DROP ET4 @ CLOSE-FILE DROP 0 EDIT-MODIFIED ! EDIT-MSG-SAVED
  EDIT-MSG ! 0 ;


  READ-LINE DUP IF DROP DROP DROP R> CLOSE-FILE DROP EDIT-MSG-READ EDIT-MSG ! 1 EXIT THEN
  DROP WHILE ET3 @ 0= IF ED-ALLOC DUP 0= IF DROP R> CLOSE-FILE DROP EDIT-MSG-BUFFER EDIT-MSG
  ! 2 EXIT THEN DUP EDIT-TAIL @ EDIT-LINK-AFTER DUP ET2 ! EDIT-LINES @ 1+ EDIT-LINES ! DROP ELSE 0
  ET3 ! THEN DUP ET2 @ EDIT-LINE-LEN ! TIB ET2 @ EDIT-LINE-TEXT ROT CMOVE REPEAT DROP R>
  CLOSE-FILE DROP EDIT-HEAD @ EDIT-CUR ! EDIT-HEAD @ EDIT-TOP ! 1 EDIT-CUR# ! 1 EDIT-TOP# ! 0

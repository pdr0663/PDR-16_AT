: EDIT-HANDLE-EKEY DUP KEY_LEFT = IF DROP EDIT-MOVE-LEFT EXIT THEN DUP KEY_RIGHT = IF DROP
EDIT-MOVE-RIGHT EXIT THEN DUP KEY_UP = IF DROP EDIT-MOVE-UP EXIT THEN DUP KEY_DOWN = IF DROP
  EDIT-MOVE-DOWN EXIT THEN DUP KEY_HOME = IF DROP EDIT-MOVE-HOME EXIT THEN DUP KEY_END = IF DROP
  EDIT-MOVE-END EXIT THEN DUP KEY_PGUP = IF DROP EDIT-PAGE-UP EXIT THEN DUP KEY_PGDN = IF DROP
  EDIT-PAGE-DOWN EXIT THEN DUP KEY_BACKSPACE = IF DROP EDIT-BACKSPACE EXIT THEN DUP KEY_DEL = IF
  DROP EDIT-DELETE-CHAR EXIT THEN DUP KEY_ENTER = IF DROP EDIT-SPLIT-LINE EXIT THEN DUP KEY_INS
  = IF DROP EDIT-INSERT @ 0= EDIT-INSERT ! EXIT THEN DUP KEY_F2 = IF DROP EDIT-SAVE DROP EXIT
  THEN DUP KEY_F4 = IF DROP EDIT-NEW EXIT THEN DUP KEY_F5 = IF DROP EDIT-COPY-LINE EXIT THEN DUP
  KEY_F7 = IF DROP EDIT-PASTE-LINE EXIT THEN DUP KEY_F8 = IF DROP EDIT-DELETE-LINE EXIT THEN DUP
  KEY_F10 = IF DROP 0 EDIT-RUNNING ! EXIT THEN DROP EDIT-MSG-UNSUP EDIT-MSG ! ;


: EDIT-CLEAR-LINE 0 OVER EDIT-LINE-LEN ! DROP ;

: ED-ALLOC EDIT-FREE @ ?DUP IF DUP @ EDIT-FREE ! ELSE EDIT-HERE @ DUP EDIT-REC-SIZE + EDIT-LIMIT
@ SWAP U< IF DROP 0 EXIT THEN DUP EDIT-REC-SIZE + EDIT-HERE ! THEN DUP 0 OVER ! SWAP DROP DUP
  EDIT-LINE-PREV 0 SWAP ! DUP EDIT-LINE-LEN 0 SWAP ! DUP EDIT-LINE-FLAGS 0 SWAP ! ;

: EDIT-FREE-LINE EDIT-FREE @ OVER ! EDIT-FREE ! ;

: EDIT-LINK-AFTER ET1 ! ET2 ! ET1 @ @ ET2 @ ! ET1 @ ET2 @ EDIT-LINE-PREV ! ET2 @ @ ?DUP IF ET2 @
SWAP EDIT-LINE-PREV ! ELSE ET1 @ EDIT-TAIL ! THEN ET1 @ ET2 @ ! ;

: EDIT-UNLINK DUP @ ET1 ! DUP EDIT-LINE-PREV @ ET2 ! ET2 @ IF ET1 @ ET2 @ ! ELSE ET1 @ EDIT-HEAD
! THEN ET1 @ IF ET2 @ ET1 @ EDIT-LINE-PREV ! ELSE ET2 @ EDIT-TAIL ! THEN ;

: EDIT-RESET-BUFFER 0 EDIT-FREE ! EDIT-BASE @ EDIT-HERE ! 0 EDIT-MODIFIED ! 0 EDIT-MSG ! 0
EDIT-COL ! 0 EDIT-PREF ! 0 EDIT-CLIP-LEN ! ED-ALLOC DUP 0= IF DROP EDIT-MSG-BUFFER EDIT-MSG !
  EXIT THEN DUP EDIT-HEAD ! DUP EDIT-TAIL ! DUP EDIT-CUR ! DUP EDIT-TOP ! DROP 1 EDIT-LINES ! 1
  EDIT-CUR# ! 1 EDIT-TOP# ! ;

: EDIT-INIT CP @ EDIT-MARK ! CP @ DUP EDIT-PATH-BUF# ! EDIT-PATH-SIZE + DUP EDIT-CLIP-BUF# !
  EDIT-LINE-CAP + DUP EDIT-BASE ! DUP EDIT-HERE ! EDIT-ARENA-SIZE + EDIT-LIMIT ! EDIT-LIMIT @ CP !
  1 EDIT-INSERT ! EDIT-MSG-NONE EDIT-MSG ! 0 EDIT-PATH-LEN ! EDIT-RESET-BUFFER ;

: EDIT-DONE EDIT-MARK @ CP ! NORMAL CURSOR-ON ;

: EDIT-TRIM-LEN DUP EDIT-LINE-LEN@ ET1 ! BEGIN ET1 @ WHILE DUP EDIT-LINE-TEXT ET1 @ 1- + C@ BL =
IF ET1 @ 1- ET1 ! ELSE DROP ET1 @ EXIT THEN REPEAT DROP 0 ;

: EDIT-EXTEND-CUR DUP EDIT-LINE-CAP > IF DROP EDIT-MSG-LONG EDIT-MSG ! 0 EXIT THEN DUP
EDIT-CUR-LEN <= IF DROP -1 EXIT THEN DUP ET1 ! EDIT-CUR-LEN ET2 ! EDIT-CUR @ EDIT-LINE-TEXT ET2
  @ + ET1 @ ET2 @ - BL FILL ET1 @ EDIT-CUR @ EDIT-LINE-LEN ! DROP -1 ;

: EDIT-ENSURE-VISIBLE BEGIN EDIT-CUR# @ EDIT-TOP# @ < WHILE EDIT-TOP @ EDIT-LINE-PREV @ EDIT-TOP
! EDIT-TOP# @ 1- EDIT-TOP# ! REPEAT BEGIN EDIT-CUR# @ EDIT-TOP# @ EDIT-TEXT-H + >= WHILE
  EDIT-TOP @ @ EDIT-TOP ! EDIT-TOP# @ 1+ EDIT-TOP# ! REPEAT ;

: EDIT-MOVE-UP EDIT-CUR @ EDIT-LINE-PREV @ ?DUP IF EDIT-CUR ! EDIT-CUR# @ 1- EDIT-CUR# !
EDIT-PREF @ EDIT-COL ! EDIT-ENSURE-VISIBLE THEN ;

: EDIT-MOVE-DOWN EDIT-CUR @ @ ?DUP IF EDIT-CUR ! EDIT-CUR# @ 1+ EDIT-CUR# ! EDIT-PREF @ EDIT-COL
! EDIT-ENSURE-VISIBLE THEN ;

: EDIT-MOVE-LEFT EDIT-COL @ IF EDIT-COL @ 1- EDIT-COL ! EDIT-COL @ EDIT-PREF ! THEN ;

: EDIT-MOVE-RIGHT EDIT-COL @ 1+ DUP EDIT-COL ! EDIT-PREF ! ;

: EDIT-MOVE-HOME 0 EDIT-COL! ;

: EDIT-MOVE-END EDIT-CUR-LEN EDIT-COL! ;

: EDIT-PAGE-UP 0 ET1 ! BEGIN ET1 @ EDIT-TEXT-H < WHILE EDIT-MOVE-UP ET1 @ 1+ ET1 ! REPEAT ;

: EDIT-PAGE-DOWN 0 ET1 ! BEGIN ET1 @ EDIT-TEXT-H < WHILE EDIT-MOVE-DOWN ET1 @ 1+ ET1 ! REPEAT ;

: EDIT-SET-MODIFIED -1 EDIT-MODIFIED ! EDIT-MSG-NONE EDIT-MSG ! ;

: EDIT-OVERWRITE-CHAR EDIT-COL @ 1+ EDIT-EXTEND-CUR 0= IF DROP EXIT THEN EDIT-COL @ EDIT-CUR @
EDIT-LINE-ADDR C! EDIT-COL @ 1+ EDIT-COL! EDIT-SET-MODIFIED ;

: EDIT-INSERT-CHAR EDIT-COL @ ET3 ! EDIT-CUR-LEN ET4 ! ET3 @ ET4 @ >= IF ET3 @ 1+ EDIT-EXTEND-CUR
0= IF DROP EXIT THEN EDIT-COL @ EDIT-CUR @ EDIT-LINE-ADDR C! ELSE ET4 @ 1+ EDIT-EXTEND-CUR 0= IF
  DROP EXIT THEN ET3 @ EDIT-CUR @ EDIT-LINE-ADDR DUP 1+ SWAP ET4 @ ET3 @ - CMOVE> EDIT-COL @
  EDIT-CUR @ EDIT-LINE-ADDR C! THEN EDIT-COL @ 1+ EDIT-COL! EDIT-SET-MODIFIED ;

: EDIT-JOIN-NEXT EDIT-CUR @ @ ?DUP 0= IF DROP EXIT THEN DUP ET1 ! EDIT-CUR-LEN ET2 ! ET1 @
EDIT-LINE-LEN@ ET3 ! ET2 @ ET3 @ + EDIT-LINE-CAP > IF EDIT-MSG-LONG EDIT-MSG ! EXIT THEN ET1 @
  EDIT-LINE-TEXT EDIT-CUR @ EDIT-LINE-TEXT ET2 @ + ET3 @ CMOVE ET2 @ ET3 @ + EDIT-CUR @
  EDIT-LINE-LEN ! ET1 @ EDIT-UNLINK ET1 @ EDIT-FREE-LINE EDIT-LINES @ 1- EDIT-LINES !
  EDIT-SET-MODIFIED ;

: EDIT-DELETE-CHAR EDIT-COL @ ET1 ! EDIT-CUR-LEN ET2 ! ET1 @ ET2 @ < IF EDIT-CUR @ ET1 @ 1+
EDIT-LINE-ADDR EDIT-CUR @ ET1 @ EDIT-LINE-ADDR ET2 @ ET1 @ - 1- CMOVE ET2 @ 1- EDIT-CUR @
  EDIT-LINE-LEN ! EDIT-SET-MODIFIED EXIT THEN ET1 @ ET2 @ = IF EDIT-JOIN-NEXT THEN ;

: EDIT-SPLIT-LINE ED-ALLOC DUP 0= IF DROP EDIT-MSG-BUFFER EDIT-MSG ! EXIT THEN DUP ET1 !
EDIT-CUR @ ET2 ! EDIT-COL @ ET3 ! ET2 @ EDIT-LINE-LEN@ ET4 ! ET3 @ ET4 @ < IF ET4 @ ET3 @ - DUP
  ET1 @ EDIT-LINE-LEN ! ET2 @ EDIT-LINE-TEXT ET3 @ + ET1 @ EDIT-LINE-TEXT ROT CMOVE ET3 @ ET2 @
  EDIT-LINE-LEN ! ELSE 0 ET1 @ EDIT-LINE-LEN ! THEN ET1 @ ET2 @ EDIT-LINK-AFTER EDIT-LINES @ 1+
  EDIT-LINES ! ET1 @ EDIT-CUR ! EDIT-CUR# @ 1+ EDIT-CUR# ! 0 EDIT-COL! EDIT-ENSURE-VISIBLE
  EDIT-SET-MODIFIED ;

: EDIT-BACKSPACE EDIT-COL @ 0= IF EDIT-CUR @ EDIT-LINE-PREV @ ?DUP IF DUP EDIT-LINE-LEN@ ET1 !
EDIT-CUR ! EDIT-CUR# @ 1- EDIT-CUR# ! ET1 @ EDIT-COL! EDIT-JOIN-NEXT EDIT-ENSURE-VISIBLE THEN
  EXIT THEN EDIT-COL @ 1- DUP EDIT-COL ! EDIT-PREF ! EDIT-COL @ EDIT-CUR-LEN >= IF EXIT THEN
  EDIT-DELETE-CHAR ;

: EDIT-DELETE-LINE EDIT-LINES @ 1 = IF EDIT-CUR @ EDIT-CLEAR-LINE 0 EDIT-COL! EDIT-SET-MODIFIED
EXIT THEN EDIT-CUR @ ET1 ! ET1 @ @ ?DUP IF DUP EDIT-CUR ! ELSE ET1 @ EDIT-LINE-PREV @ DUP
  EDIT-CUR ! EDIT-CUR# @ 1- EDIT-CUR# ! THEN ET1 @ EDIT-TOP @ = IF EDIT-CUR @ EDIT-TOP !
  EDIT-CUR# @ EDIT-TOP# ! THEN ET1 @ EDIT-UNLINK ET1 @ EDIT-FREE-LINE EDIT-LINES @ 1- EDIT-LINES
  ! EDIT-CUR-LEN EDIT-COL @ MIN EDIT-COL! EDIT-ENSURE-VISIBLE EDIT-SET-MODIFIED ;

: EDIT-COPY-LINE EDIT-CUR @ EDIT-LINE-LEN@ DUP EDIT-CLIP-LEN ! EDIT-CUR @ EDIT-LINE-TEXT
EDIT-CLIP-BUF ROT CMOVE EDIT-MSG-NONE EDIT-MSG ! ;

: EDIT-PASTE-LINE ED-ALLOC DUP 0= IF DROP EDIT-MSG-BUFFER EDIT-MSG ! EXIT THEN DUP ET1 !
EDIT-CLIP-LEN @ DUP ET1 @ EDIT-LINE-LEN ! EDIT-CLIP-BUF ET1 @ EDIT-LINE-TEXT ROT CMOVE ET1 @
  EDIT-CUR @ EDIT-LINK-AFTER ET1 @ EDIT-CUR ! EDIT-LINES @ 1+ EDIT-LINES ! EDIT-CUR# @ 1+
  EDIT-CUR# ! 0 EDIT-COL! EDIT-ENSURE-VISIBLE EDIT-SET-MODIFIED ;

